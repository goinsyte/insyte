/*
 * The `auth` schema migration, written from better-auth's own table list for our configuration (12 §3, S11).
 *
 *   bun run auth:schema          writes packages/modules/src/shared/tables/migrations/0003_auth.ts
 *   bun run auth:check           fails when that file is not what the configuration implies (in hygiene, so in CI)
 *
 * better-auth's migrations are never run: our Migrator applies this file like any other. Changing a plugin or an option
 * that adds columns means a new migration, never an edit of a merged one (migrations:check).
 */
import { getAuthTables } from "better-auth/db"
import { readFileSync, writeFileSync } from "node:fs"
import { authOptions } from "../packages/integrations/better-auth/src/Auth.ts"

const TARGET = "packages/modules/src/shared/tables/migrations/0003_auth.ts"

const options = authOptions(
  { execute: async () => [], baseURL: "http://localhost", secret: "schema-generation-only", sendMail: async () => {} },
  undefined
)
const tables = getAuthTables(options)

const columnType = (type: unknown): string => {
  if (Array.isArray(type)) return "text"
  switch (type) {
    case "string":
      return "text"
    case "number":
      return "integer"
    case "boolean":
      return "boolean"
    case "date":
      return "timestamptz"
    case "json":
    case "string[]":
    case "number[]":
      return "jsonb"
    default:
      throw new Error(`auth-schema: better-auth field type ${String(type)} has no column type here; add it`)
  }
}

interface Field {
  readonly type: unknown
  readonly required?: boolean
  readonly unique?: boolean
  readonly index?: boolean
  readonly fieldName?: string
  readonly defaultValue?: unknown
  readonly references?: { readonly model: string; readonly field: string; readonly onDelete?: string }
}

const statements: Array<string> = ["create schema auth", "alter schema auth owner to insyte_owner"]
const indexes: Array<string> = []
const nameOf = (model: string) => tables[model]?.modelName ?? model
// Quoted: `user` is a reserved word in Postgres.
const q = (identifier: string) => `"${identifier}"`

for (const table of Object.values(tables)) {
  const columns = ["id text primary key"]
  for (const [key, raw] of Object.entries(table.fields)) {
    const field = raw as Field
    const column = field.fieldName ?? key
    const parts = [`${column} ${columnType(field.type)}`]
    if (field.required === true) parts.push("not null")
    if (field.unique === true) parts.push("unique")
    if (typeof field.defaultValue === "boolean" || typeof field.defaultValue === "number") {
      parts.push(`default ${String(field.defaultValue)}`)
    }
    if (field.references !== undefined) {
      parts.push(
        `references auth.${q(nameOf(field.references.model))}(${field.references.field}) on delete ${
          field.references.onDelete ?? "cascade"
        }`
      )
    }
    if (field.references !== undefined || field.index === true) {
      indexes.push(`create index ${table.modelName}_${column} on auth.${q(table.modelName)} (${column})`)
    }
    columns.push(parts.join(" "))
  }
  statements.push(`create table auth.${q(table.modelName)} (\n     ${columns.join(",\n     ")}\n   )`)
}
statements.push(
  ...indexes,
  // Not tenant tables and not under RLS: they are better-auth's, read and written only through it as insyte_app.
  "grant usage on schema auth to insyte_app",
  "grant select, insert, update, delete on all tables in schema auth to insyte_app"
)

const source = `import { statements } from "../statements.ts"

/**
 * better-auth's tables in their own schema \`auth\` (12 §3). GENERATED by \`bun run auth:schema\` from
 * \`packages/integrations/better-auth/src/Auth.ts\`; \`bun run auth:check\` keeps the two in step. Do not edit by hand.
 */
export default statements(
${statements.map((s) => `  \`${s}\``).join(",\n")}
)
`

if (process.argv.includes("--check")) {
  let current = ""
  try {
    current = readFileSync(TARGET, "utf8")
  } catch {
    // missing: reported below
  }
  if (current !== source) {
    console.error(
      `auth:check: ${TARGET} is not what Auth.ts implies. Run bun run auth:schema (as a new migration once merged).`
    )
    process.exit(1)
  }
  console.log("auth:check: the auth schema matches the better-auth configuration")
} else {
  writeFileSync(TARGET, source)
  console.log(`auth:schema: wrote ${TARGET} (${Object.keys(tables).length} tables)`)
}
