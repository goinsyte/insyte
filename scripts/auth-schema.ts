/*
 * The `auth` schema's migrations, written from better-auth's own table list for our configuration (12 §3, S11).
 *
 *   bun run auth:schema -- --name two_factor   writes the next NNNN_auth_two_factor.ts with what the configuration adds
 *   bun run auth:check                         fails when the auth migrations do not create what the configuration implies
 *
 * better-auth's migrations are never run: our Migrator applies these files like any other. A merged migration is never
 * edited (migrations:check), so a plugin or an option that adds tables or columns becomes a new migration holding only
 * the difference: what the configuration implies, minus what the migrations this script wrote already create. Nothing is ever
 * dropped here; a table or column the configuration no longer has is reported, for a hand-written migration.
 */
import { getAuthTables } from "better-auth/db"
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { authOptions } from "../packages/integrations/better-auth/src/Auth.ts"

const DIR = "packages/modules/src/shared/tables/migrations"

// Every option that adds a table or a column is on: the generated schema is what any stage could need.
const options = authOptions(
  { execute: async () => [], baseURL: "http://localhost", secret: "schema-generation-only", sendMail: async () => {} },
  undefined
)
const tables = getAuthTables(options)

const columnType = (type: unknown): string => {
  if (Array.isArray(type)) return "text"
  switch (type) {
    case "string":
      return "text"
    case "number":
      return "integer"
    case "boolean":
      return "boolean"
    case "date":
      return "timestamptz"
    case "json":
    case "string[]":
    case "number[]":
      return "jsonb"
    default:
      throw new Error(`auth-schema: better-auth field type ${String(type)} has no column type here; add it`)
  }
}

interface Field {
  readonly type: unknown
  readonly required?: boolean
  readonly unique?: boolean
  readonly index?: boolean
  readonly fieldName?: string
  readonly defaultValue?: unknown
  readonly references?: { readonly model: string; readonly field: string; readonly onDelete?: string }
}

const nameOf = (model: string) => tables[model]?.modelName ?? model
// Quoted: `user` is a reserved word in Postgres.
const q = (identifier: string) => `"${identifier}"`

/** What the configuration implies: per table, its columns in order, each with its definition and its index. */
const desired = new Map<string, Array<{ column: string; definition: string; index: string | undefined }>>()
for (const table of Object.values(tables)) {
  const columns: Array<{ column: string; definition: string; index: string | undefined }> = []
  for (const [key, raw] of Object.entries(table.fields)) {
    const field = raw as Field
    const column = field.fieldName ?? key
    const parts = [`${column} ${columnType(field.type)}`]
    if (field.required === true) parts.push("not null")
    if (field.unique === true) parts.push("unique")
    if (typeof field.defaultValue === "boolean" || typeof field.defaultValue === "number") {
      parts.push(`default ${String(field.defaultValue)}`)
    }
    if (field.references !== undefined) {
      parts.push(
        `references auth.${q(nameOf(field.references.model))}(${field.references.field}) on delete ${
          field.references.onDelete ?? "cascade"
        }`
      )
    }
    const index = field.references !== undefined || field.index === true
      ? `create index ${table.modelName}_${column} on auth.${q(table.modelName)} (${column})`
      : undefined
    columns.push({ column, definition: parts.join(" "), index })
  }
  desired.set(table.modelName, columns)
}

/** What the `NNNN_auth*` migrations create, read back from their SQL: per table, its columns. */
// The ones this script wrote, by their header: `auth_events` (0007) is ours, not better-auth's.
const authMigrations = readdirSync(DIR)
  .filter((f) => /^\d{4}_.*\.ts$/.test(f))
  .filter((f) => readFileSync(join(DIR, f), "utf8").includes("GENERATED by `bun run auth:schema`"))
  .sort()
const existing = new Map<string, Set<string>>()
for (const file of authMigrations) {
  const source = readFileSync(join(DIR, file), "utf8")
  for (const m of source.matchAll(/create table auth\."([a-z_]+)" \(([\s\S]*?)\n\s*\)`/g)) {
    const columns = m[2]!.split(",\n").map((line) => line.trim().split(/\s+/)[0]!).filter(Boolean)
    existing.set(m[1]!, new Set(columns))
  }
  for (const m of source.matchAll(/alter table auth\."([a-z_]+)" add column ([a-z_]+)/g)) {
    existing.get(m[1]!)?.add(m[2]!)
  }
}

const statements: Array<string> = []
const indexes: Array<string> = []
const grants: Array<string> = []
const removed: Array<string> = []
for (const [table, columns] of desired) {
  const known = existing.get(table)
  if (known === undefined) {
    statements.push(
      `create table auth.${q(table)} (\n     ${
        ["id text primary key", ...columns.map((c) => c.definition)].join(",\n     ")
      }\n   )`
    )
    indexes.push(...columns.flatMap((c) => (c.index === undefined ? [] : [c.index])))
    // Not a tenant table and not under RLS: better-auth's, read and written only through it as insyte_app.
    grants.push(`grant select, insert, update, delete on auth.${q(table)} to insyte_app`)
    continue
  }
  for (const c of columns) {
    if (known.has(c.column)) continue
    statements.push(`alter table auth.${q(table)} add column ${c.definition}`)
    if (c.index !== undefined) indexes.push(c.index)
  }
  for (const column of known) {
    if (column !== "id" && !columns.some((c) => c.column === column)) removed.push(`auth.${table}.${column}`)
  }
}
for (const table of existing.keys()) if (!desired.has(table)) removed.push(`auth.${table}`)

const additions = [...statements, ...indexes, ...grants]

if (process.argv.includes("--check")) {
  if (additions.length > 0 || removed.length > 0) {
    console.error(
      `auth:check: the auth migrations do not create what Auth.ts implies.${
        additions.length > 0 ? `\n  missing: ${additions.map((s) => s.split("\n")[0]).join("; ")}` : ""
      }${
        removed.length > 0 ? `\n  no longer configured: ${removed.join(", ")}` : ""
      }\n  Run bun run auth:schema -- --name <what>.`
    )
    process.exit(1)
  }
  console.log(`auth:check: the auth schema matches the better-auth configuration (${authMigrations.join(", ")})`)
} else {
  const at = process.argv.indexOf("--name")
  const name = at === -1 ? undefined : process.argv[at + 1]
  if (additions.length === 0) {
    console.log("auth:schema: nothing to add")
    process.exit(removed.length > 0 ? 1 : 0)
  }
  if (name === undefined || !/^[a-z_]+$/.test(name)) {
    console.error("auth:schema: name the migration, --name <snake_case>")
    process.exit(1)
  }
  const next = Math.max(...readdirSync(DIR).map((f) => Number(f.slice(0, 4))).filter(Number.isFinite)) + 1
  const target = join(DIR, `${String(next).padStart(4, "0")}_auth_${name}.ts`)
  writeFileSync(
    target,
    `import { statements } from "../statements.ts"

/**
 * What better-auth's configuration adds to the \`auth\` schema (12 §3). GENERATED by \`bun run auth:schema\` from
 * \`packages/integrations/better-auth/src/Auth.ts\`; \`bun run auth:check\` keeps the two in step. Do not edit by hand.
 */
export default statements(
${additions.map((s) => `  \`${s}\``).join(",\n")}
)
`
  )
  console.log(`auth:schema: wrote ${target}; add it to Migrations.ts`)
  if (removed.length > 0) console.error(`auth:schema: no longer configured, not dropped: ${removed.join(", ")}`)
}
