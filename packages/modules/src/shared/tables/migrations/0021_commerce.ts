import { tenantTable } from "@insyte/database/Tenancy"
import { statements } from "../statements.ts"

/**
 * The commerce mirror (M6.3; domain.md §4): what Shopify owns, as Insyte keeps it. One row per Shopify object and
 * store (`shopify_id` is the number in its gid), written by the sync only: the backfill, webhooks and the reconcile
 * sweep. Every row carries `external_updated_at`, and an upsert only overwrites with something at least as new (the
 * ordering guard, §4.6). Children carry `workspace_id` too, so every table sits behind the workspace policy on its
 * own. Members only until the partner portals (M8, M16) add their narrow policies. Insyte's own fields beside these
 * (suppliers, costs, delays) arrive with the milestones that write them.
 */
export default statements(
  `create table products (
     id                  text primary key,
     workspace_id        text not null references workspaces(id) on delete cascade,
     store_id            text not null references stores(id) on delete cascade,
     shopify_id          text not null,
     title               text not null,
     handle              text not null,
     description_html    text not null default '',
     status              text not null check (status in ('active', 'draft', 'archived')),
     vendor              text,
     product_type        text,
     tags                text[] not null default '{}',
     images              text[] not null default '{}',
     shopify_created_at  timestamptz,
     external_updated_at timestamptz not null,
     raw                 jsonb not null default '{}'
   )`,
  "create unique index products_shopify on products (store_id, shopify_id)",
  "create index products_list on products (workspace_id, store_id, title)",
  tenantTable("products", { membersOnly: true }),
  `create table variants (
     id                text primary key,
     workspace_id      text not null references workspaces(id) on delete cascade,
     store_id          text not null references stores(id) on delete cascade,
     product_id        text not null references products(id) on delete cascade,
     shopify_id        text not null,
     inventory_item_id text,
     sku               text,
     title             text not null,
     price_minor       bigint not null,
     compare_at_minor  bigint,
     position          integer not null default 1
   )`,
  "create unique index variants_shopify on variants (store_id, shopify_id)",
  "create index variants_product on variants (product_id, position)",
  "create index variants_sku on variants (workspace_id, sku) where sku is not null",
  tenantTable("variants", { membersOnly: true }),
  `create table inventory_levels (
     workspace_id text not null references workspaces(id) on delete cascade,
     variant_id   text not null references variants(id) on delete cascade,
     location_id  text not null,
     available    integer not null,
     source       text not null default 'shopify' check (source in ('shopify', 'supplier')),
     reported_by  text,
     reported_at  timestamptz not null default now(),
     primary key (variant_id, location_id, source)
   )`,
  tenantTable("inventory_levels", { membersOnly: true }),
  `create table customers (
     id                   text primary key,
     workspace_id         text not null references workspaces(id) on delete cascade,
     store_id             text not null references stores(id) on delete cascade,
     shopify_id           text not null,
     email                text,
     name                 text not null default '',
     phone                text,
     address              jsonb,
     country              text,
     tags                 text[] not null default '{}',
     orders_count         integer not null default 0,
     lifetime_value_minor bigint not null default 0,
     currency             text,
     marketing_consent    boolean not null default false,
     first_order_at       timestamptz,
     last_order_at        timestamptz,
     deleted_at           timestamptz,
     external_updated_at  timestamptz not null,
     raw                  jsonb not null default '{}'
   )`,
  "create unique index customers_shopify on customers (store_id, shopify_id)",
  "create index customers_email on customers (workspace_id, lower(email)) where email is not null",
  tenantTable("customers", { membersOnly: true }),
  `create table orders (
     id                  text primary key,
     workspace_id        text not null references workspaces(id) on delete cascade,
     store_id            text not null references stores(id) on delete cascade,
     shopify_id          text not null,
     number              text not null,
     customer_id         text references customers(id) on delete set null,
     customer_shopify_id text,
     customer_name       text not null default '',
     customer_email      text,
     status              text not null check (status in
                           ('placed', 'paid', 'at_supplier', 'shipped', 'delivered', 'cancelled', 'refunded')),
     payment_status      text not null check (payment_status in
                           ('pending', 'paid', 'partially_refunded', 'refunded', 'voided')),
     fulfillment_status  text not null check (fulfillment_status in ('unfulfilled', 'partial', 'fulfilled', 'returned')),
     total_minor         bigint not null,
     subtotal_minor      bigint not null,
     shipping_minor      bigint not null,
     tax_minor           bigint not null,
     discounts_minor     bigint not null,
     currency            text not null,
     payment_gateway     text,
     card_last4          text,
     shipping_address    jsonb,
     tags                text[] not null default '{}',
     note                text,
     channel             text,
     landing_site        text,
     referral_code       text,
     placed_at           timestamptz not null,
     paid_at             timestamptz,
     shipped_at          timestamptz,
     cancelled_at        timestamptz,
     refunded_at         timestamptz,
     is_draft            boolean not null default false,
     external_updated_at timestamptz not null,
     raw                 jsonb not null default '{}'
   )`,
  "create unique index orders_shopify on orders (store_id, shopify_id)",
  "create index orders_list on orders (workspace_id, placed_at desc, id desc)",
  "create index orders_customer on orders (customer_id, placed_at desc) where customer_id is not null",
  "create index orders_customer_shopify on orders (store_id, customer_shopify_id) where customer_shopify_id is not null",
  tenantTable("orders", { membersOnly: true }),
  `create table order_lines (
     id               text primary key,
     workspace_id     text not null references workspaces(id) on delete cascade,
     store_id         text not null references stores(id) on delete cascade,
     order_id         text not null references orders(id) on delete cascade,
     shopify_id       text not null,
     product_id       text references products(id) on delete set null,
     variant_id       text references variants(id) on delete set null,
     variant_shopify_id text,
     sku              text,
     title            text not null,
     variant_title    text,
     quantity         integer not null,
     unit_price_minor bigint not null
   )`,
  "create unique index order_lines_shopify on order_lines (store_id, shopify_id)",
  "create index order_lines_order on order_lines (order_id)",
  tenantTable("order_lines", { membersOnly: true }),
  `create table fulfilments (
     id              text primary key,
     workspace_id    text not null references workspaces(id) on delete cascade,
     store_id        text not null references stores(id) on delete cascade,
     order_id        text not null references orders(id) on delete cascade,
     shopify_id      text not null,
     status          text not null,
     carrier         text,
     tracking_number text,
     tracking_url    text,
     created_by      text not null default 'shopify' check (created_by in ('shopify', 'member', 'supplier_contact')),
     shipped_at      timestamptz,
     delivered_at    timestamptz,
     tracking_status text check (tracking_status in
                       ('in_transit', 'out_for_delivery', 'delivered', 'exception', 'returned'))
   )`,
  "create unique index fulfilments_shopify on fulfilments (store_id, shopify_id)",
  "create index fulfilments_order on fulfilments (order_id)",
  tenantTable("fulfilments", { membersOnly: true }),
  `create table refunds (
     id           text primary key,
     workspace_id text not null references workspaces(id) on delete cascade,
     store_id     text not null references stores(id) on delete cascade,
     order_id     text not null references orders(id) on delete cascade,
     shopify_id   text not null,
     amount_minor bigint not null,
     currency     text not null,
     reason       text,
     note         text,
     restock      boolean not null default false,
     status       text not null default 'succeeded' check (status in ('pending', 'succeeded', 'failed')),
     created_by   text not null default 'shopify',
     created_at   timestamptz not null
   )`,
  "create unique index refunds_shopify on refunds (store_id, shopify_id)",
  "create index refunds_order on refunds (order_id)",
  tenantTable("refunds", { membersOnly: true })
)
