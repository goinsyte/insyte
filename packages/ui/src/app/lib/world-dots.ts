export type MapView = keyof typeof RAW;

export type Grid = { cols: number; rows: number; land: ReadonlyArray<readonly [number, number]>; project: (lon: number, lat: number) => { x: number; y: number } };

const build = (r: Raw): Grid => ({
	cols: r.cols,
	rows: r.rows.length,
	land: r.rows.flatMap((hex, y) =>
		[...hex].flatMap((h, i) => {
			const n = Number.parseInt(h, 16);
			return [8, 4, 2, 1].flatMap((bit, j) => (n & bit && i * 4 + j < r.cols ? [[i * 4 + j, y] as const] : []));
		}),
	),
	project: (lon, lat) => ({ x: (lon - r.left) / r.step, y: (r.top - lat) / r.step }),
});

export const GRIDS: Record<MapView, Grid> = { world: build(RAW.world), europe: build(RAW.europe), america: build(RAW.america) };
